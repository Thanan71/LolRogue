import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { readAuthorityVersionRegistry } from './lib/authority-version-registry.mjs';

export const AUTHORITY_RESOLVER_PATH =
  'supabase/functions/verify-run/authority-version-resolver.generated.ts';
export const CLIENT_CAPABILITIES_PATH = 'src/game/authority/versionCapabilities.generated.ts';
export const CLIENT_REPLAY_PATH = 'src/game/authority/versionClientReplay.generated.ts';
const CLIENT_AUTHORITY_FEATURES = [
  'canonicalProgression',
  'manualCombat',
  'canonicalEncounters',
  'runProgression',
  'runProgressionAssists',
];

export function renderAuthorityResolver(registry) {
  const replayable = registry.versions.filter((version) => version.status !== 'unsupported');
  const imports = replayable
    .map((version, index) => {
      const modulePath = `./${path.basename(version.bundle)}`;
      return `  ${JSON.stringify(version.engine)}: () => import(${JSON.stringify(modulePath)}), // loader-${index}`;
    })
    .join('\n');

  return `// @ts-nocheck
// Generated from config/authority-versions.json by npm run authority:generate.
// Do not edit this file directly.

export const AUTHORITY_VERSION_REGISTRY = ${JSON.stringify(registry.versions, null, 2)} as const;

const verifierLoaders = {
${imports}
} as const;

export async function resolveAuthorityVerifier(engineVersion: string, contentHash: string) {
  const metadata = AUTHORITY_VERSION_REGISTRY.find(
    (candidate) => candidate.engine === engineVersion && candidate.contentHash === contentHash,
  );
  if (!metadata || metadata.status === 'unsupported') return undefined;
  const authority = await verifierLoaders[metadata.engine]();
  return authority.getAuthorityVerifier(engineVersion, contentHash);
}
`;
}

export function renderClientCapabilities(registry) {
  const current = registry.versions.find((version) => version.status === 'current');
  const featureBits = Object.fromEntries(
    CLIENT_AUTHORITY_FEATURES.map((feature, index) => [feature, 2 ** index]),
  );
  const highestEngineNumber = Math.max(...registry.versions.map((version) => version.gameplay));
  const engineMasks = Array.from({ length: highestEngineNumber + 1 }, () => -1);
  const engineChampionCatalogs = Array.from({ length: highestEngineNumber + 1 }, () => -1);
  for (const version of registry.versions) {
    const engineNumber = version.gameplay;
    engineChampionCatalogs[engineNumber] = version.championCatalog;
    engineMasks[engineNumber] = CLIENT_AUTHORITY_FEATURES.reduce(
      (mask, feature) => mask | (version.features[feature] ? featureBits[feature] : 0),
      0,
    );
  }
  return `// Generated from config/authority-versions.json by npm run authority:generate.
// Do not edit this file directly.

export const AUTHORITY_GAMEPLAY_RELEASE_LABELS: Readonly<Record<number, string>> = ${JSON.stringify(Object.fromEntries(registry.versions.filter((version) => /^run-engine-\d+\.\d+\.\d+$/.test(version.engine)).map((version) => [version.gameplay, version.rulesetCode])))};
export const AUTHORITY_ENGINE_VERSION_ORDINALS: Readonly<Record<string, number>> = ${JSON.stringify(Object.fromEntries(registry.versions.map((version) => [version.engine, version.gameplay])))};
export const AUTHORITY_FEATURE_BITS = ${JSON.stringify(featureBits)} as const;
export const AUTHORITY_ENGINE_FEATURE_MASKS: readonly number[] = ${JSON.stringify(engineMasks)};
export const AUTHORITY_ENGINE_CHAMPION_CATALOGS: readonly number[] = ${JSON.stringify(engineChampionCatalogs)};
export const CURRENT_AUTHORITY_ENGINE = ${JSON.stringify(current.engine)};
export const CURRENT_AUTHORITY_CHAMPION_CATALOG = ${current.championCatalog};
export const CURRENT_AUTHORITY_VERSION = ${JSON.stringify(
    {
      engine: current.engine,
      gameplay: current.gameplay,
      progression: current.progression,
      contentHash: current.contentHash,
      dailyScore: current.dailyScore,
    },
    null,
    2,
  )} as const;
`;
}

export function renderClientReplay(registry) {
  const replayable = registry.versions.filter((version) => version.status === 'replay-only');
  const imports = replayable
    .map((version) => {
      const modulePath = path.posix.relative('src/game/authority', version.bundle);
      return `  ${JSON.stringify(version.engine)}: async () => {
    const authority = await import(${JSON.stringify(modulePath)});
    return authority.getAuthorityVerifier(${JSON.stringify(version.engine)}, ${JSON.stringify(version.contentHash)}) as unknown as HistoricalAuthorityVerifier | undefined;
  },`;
    })
    .join('\n');
  return `// Generated from config/authority-versions.json by npm run authority:generate.
// Do not edit this file directly.
import type { HistoricalAuthorityVerifier } from './historicalAuthority';

export const HISTORICAL_AUTHORITY_ENGINES: readonly string[] = ${JSON.stringify(replayable.map(({ engine }) => engine))};
const verifierLoaders: Readonly<Record<string, () => Promise<HistoricalAuthorityVerifier | undefined>>> = {
${imports}
};

export async function loadHistoricalAuthorityVerifier(engineVersion: string): Promise<HistoricalAuthorityVerifier | undefined> {
  return verifierLoaders[engineVersion]?.();
}
`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const registry = await readAuthorityVersionRegistry();
  await Promise.all([
    writeFile(AUTHORITY_RESOLVER_PATH, renderAuthorityResolver(registry)),
    writeFile(CLIENT_CAPABILITIES_PATH, renderClientCapabilities(registry)),
    writeFile(CLIENT_REPLAY_PATH, renderClientReplay(registry)),
  ]);
}
