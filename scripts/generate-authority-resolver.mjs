import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { readAuthorityVersionRegistry } from './lib/authority-version-registry.mjs';

export const AUTHORITY_RESOLVER_PATH =
  'supabase/functions/verify-run/authority-version-resolver.generated.ts';

export function renderAuthorityResolver(registry) {
  const replayable = registry.versions.filter((version) => version.status !== 'unsupported');
  const imports = replayable
    .map((version, index) => {
      const modulePath = `./${path.basename(version.bundle)}`;
      return `  ${JSON.stringify(version.engine)}: () => import(${JSON.stringify(modulePath)}), // loader-${index}`;
    })
    .join('\n');

  return `// @ts-nocheck
// Generated from config/authority-versions.json by npm run authority:generate.
// Do not edit this file directly.

export const AUTHORITY_VERSION_REGISTRY = ${JSON.stringify(registry.versions, null, 2)} as const;

const verifierLoaders = {
${imports}
} as const;

export async function resolveAuthorityVerifier(engineVersion: string, contentHash: string) {
  const metadata = AUTHORITY_VERSION_REGISTRY.find(
    (candidate) => candidate.engine === engineVersion && candidate.contentHash === contentHash,
  );
  if (!metadata || metadata.status === 'unsupported') return undefined;
  const authority = await verifierLoaders[metadata.engine]();
  return authority.getAuthorityVerifier(engineVersion, contentHash);
}
`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const registry = await readAuthorityVersionRegistry();
  await writeFile(AUTHORITY_RESOLVER_PATH, renderAuthorityResolver(registry));
}
